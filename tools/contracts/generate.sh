#!/usr/bin/env bash
# Regenerates every service contract artefact. Run via `make contracts`; CI runs
# `make contracts-check` and fails if the committed output is stale.
#
#   ai-api (FastAPI)  -> openapi/ai-api.openapi.json  -> src/generated/ai-api.ts (types for openapi-fetch)
#   backend (NestJS)  -> openapi/backend.openapi.json (schemas come from the @docqa/contracts models)
#   events/*.schema.json -> src/generated/<event>.ts + docqa_core/events/<event>.py (pydantic)
set -euo pipefail

CONTRACTS=libs/shared/contracts
PY_EVENTS=libs/py-core/src/docqa_core/events
RAW_BACKEND=dist/backend.openapi.raw.json

echo '> ai-api OpenAPI'
uv run python -m docqa_ai_api.openapi "$CONTRACTS/openapi/ai-api.openapi.json"
pnpm exec openapi-typescript "$CONTRACTS/openapi/ai-api.openapi.json" \
    -o "$CONTRACTS/src/generated/ai-api.ts"

echo '> backend OpenAPI'
pnpm nx build backend --outputStyle=static
# The export builds the Nest app without listening; Prisma connects lazily, so no DB is needed.
DATABASE_URL=postgresql://openapi:unused@localhost:5432/unused \
    node dist/apps/backend/main.js --export-openapi="$RAW_BACKEND"
node tools/contracts/backend-openapi.mjs "$RAW_BACKEND" "$CONTRACTS/openapi/backend.openapi.json"

echo '> events'
for schema in "$CONTRACTS"/events/*.schema.json; do
    name=$(basename "$schema" .schema.json)
    module=$(echo "$name" | tr '.-' '__')
    pnpm exec json2ts -i "$schema" -o "$CONTRACTS/src/generated/$name.ts" \
        --bannerComment "/* Generated by \`make contracts\` from $schema. Do not edit. */"
    uv run datamodel-codegen --input "$schema" --input-file-type jsonschema \
        --output "$PY_EVENTS/$module.py" \
        --output-model-type pydantic_v2.BaseModel --target-python-version 3.12 \
        --snake-case-field --allow-population-by-field-name --use-standard-collections \
        --use-union-operator --use-double-quotes --disable-timestamp \
        --output-datetime-class AwareDatetime --formatters ruff-format ruff-check \
        --use-schema-description \
        --custom-file-header "\"\"\"Generated by \`make contracts\` from $name.schema.json. Do not edit.\"\"\""
done

echo '> format'
pnpm exec prettier --write --log-level warn "$CONTRACTS/openapi" "$CONTRACTS/events" "$CONTRACTS/src/generated"
# datamodel-codegen writes CRLF on Windows; keep the output identical on every OS
sed -i 's/\r$//' "$PY_EVENTS"/*.py
uv run ruff check --fix --quiet "$PY_EVENTS"
uv run ruff format --quiet "$PY_EVENTS"
