"""Column and constraint helpers shared by the ORM mirror modules."""

import enum
import uuid
from datetime import datetime

import sqlalchemy as sa
from sqlalchemy import ForeignKey, ForeignKeyConstraint
from sqlalchemy.dialects import postgresql
from sqlalchemy.orm import Mapped, mapped_column

UUIDV7 = sa.text("uuidv7()")


def enum_type(py_enum: type[enum.StrEnum], name: str) -> sa.Enum:
    """VarChar(32) holding the enum's values. The CHECK constraint lives in the migration."""
    return sa.Enum(
        py_enum,
        native_enum=False,
        create_constraint=False,
        length=32,
        name=name,
        values_callable=lambda e: [m.value for m in e],
    )


def uuid_pk() -> Mapped[uuid.UUID]:
    """UUIDv7 primary key generated by the database."""
    return mapped_column(postgresql.UUID(as_uuid=True), primary_key=True, server_default=UUIDV7)


def tenant_fk() -> Mapped[uuid.UUID]:
    """``tenant_id`` referencing ``tenants`` with cascade (the tenant purge path)."""
    return mapped_column(ForeignKey("tenants.id", ondelete="CASCADE"))


def created_ts() -> Mapped[datetime]:
    """``created_at`` with a server default."""
    return mapped_column(sa.DateTime(timezone=True), server_default=sa.func.now())


def opt_ts() -> Mapped[datetime | None]:
    """A nullable timestamp column."""
    return mapped_column(sa.DateTime(timezone=True))


def sha256_hex() -> sa.CHAR:
    """SHA-256 as 64 lowercase hex characters."""
    return sa.CHAR(64)


def tenant_ref(
    column: str,
    target: str,
    name: str,
    *,
    ondelete: str | None = None,
    use_alter: bool = False,
) -> ForeignKeyConstraint:
    """Composite FK ``(tenant_id, column) -> target(tenant_id, id)`` (ADR 0006).

    ``use_alter`` breaks a reference cycle (documents <-> document_versions).
    """
    return ForeignKeyConstraint(
        ["tenant_id", column],
        [f"{target}.tenant_id", f"{target}.id"],
        name=name,
        ondelete=ondelete,
        use_alter=use_alter,
    )
